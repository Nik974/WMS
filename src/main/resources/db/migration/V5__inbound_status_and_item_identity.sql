DO $$
    BEGIN
        IF NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_name = 'inbound_items' AND column_name = 'id' AND is_identity = 'YES'
        ) AND NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_name = 'inbound_items' AND column_name = 'id' AND column_default IS NOT NULL
        ) THEN
            ALTER TABLE inbound_items ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
        END IF;
    END $$;

SELECT setval(pg_get_serial_sequence('inbound_items', 'id'),
              COALESCE((SELECT MAX(id) FROM inbound_items), 0) + 1, false);

ALTER TABLE inbound_orders DROP CONSTRAINT IF EXISTS chk_inbound_status;

UPDATE inbound_orders SET status = UPPER(status);

ALTER TABLE inbound_orders
    ADD CONSTRAINT chk_inbound_status
        CHECK (status IN ('NEW', 'RECEIVED', 'CANCELLED'));