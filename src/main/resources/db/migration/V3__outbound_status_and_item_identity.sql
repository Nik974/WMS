DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'outbound_items' AND column_name = 'id' AND is_identity = 'YES'
    ) THEN
ALTER TABLE outbound_items ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
END IF;
END $$;

SELECT setval(pg_get_serial_sequence('outbound_items', 'id'),
              COALESCE((SELECT MAX(id) FROM outbound_items), 0) + 1, false);

ALTER TABLE outbound_orders DROP CONSTRAINT IF EXISTS chk_outbound_status;

UPDATE outbound_orders SET status = CASE UPPER(status)
                                        WHEN 'NEW'        THEN 'NEW'
                                        WHEN 'INTRANSIT'  THEN 'IN_TRANSIT'
                                        WHEN 'IN_TRANSIT' THEN 'IN_TRANSIT'
                                        WHEN 'SHIPPED'    THEN 'SHIPPED'
                                        WHEN 'CANCELLED'  THEN 'CANCELLED'
                                        ELSE status
    END;

ALTER TABLE outbound_orders
    ADD CONSTRAINT chk_outbound_status
        CHECK (status IN ('NEW', 'IN_TRANSIT', 'SHIPPED', 'CANCELLED'));